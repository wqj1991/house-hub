/** 板块清单（前端可用来排序/做筛选项）。 */
export const BIZCIRCLES = Object.fromEntries(
  Object.entries(ALIASES).map(([district, map]) => [district, Object.keys(map)]),
);

/** 按别名最长匹配从「名称 + 地址」里认出板块；认不出就留空，不猜。 */
export function matchBizcircle(district, ...texts) {
  const map = ALIASES[district];
  if (!map) return "";
  const hay = texts.filter(Boolean).join(" ");
  let best = "";
  let bestLen = 0;
  for (const [name, aliases] of Object.entries(map)) {
    for (const alias of [name, ...aliases]) {
      if (alias.length > bestLen && hay.includes(alias)) {
        best = name;
        bestLen = alias.length;
      }
    }
  }
  return best;
}

