/** 已定决策的后果清单（按决策顺序）。 */
export function decisionImpacts(decisions: Record<string, string>): Array<{ decision: Decision; option: DecisionOption }> {
  const out: Array<{ decision: Decision; option: DecisionOption }> = [];
  for (const decision of DECISIONS) {
    const optionId = decisions[decision.id];
    if (!optionId) continue;
    const option = decision.options.find((item) => item.id === optionId);
    if (option) out.push({ decision, option });
  }
  return out;
}

/** 决策数：已定 / 全部。 */
export function decisionCount(decisions: Record<string, string>): number {
  return DECISIONS.filter((decision) => Boolean(decisions[decision.id])).length;
}

/** 由决策推导出的硬结论：这几句是要写进心里的。 */
export function decisionVerdicts(decisions: Record<string, string>): string[] {
  const out: string[] = [];
  const title = decisions.title_mode;
  if (title === "couple" || title === "later") {
    out.push("**双人材料**：身份证、户口本、结婚证、征信、收入证明、流水全部按 2 份准备，六处姓名必须一致。");
  }
  if (title === "couple") {
    out.push("**两人都做借款人**：双方征信都要干净；任一方有当前逾期或大额网贷，会在第 2 步被卡。");
  }
  if (decisions.qualification === "non_bj") {
    out.push("**非京籍硬门槛**：连续 2 年社保或个税，断缴补缴不算；核验结果约 30 天有效，过期重来。");
  }
  if (decisions.loan_type === "combo") {
    out.push("**组合贷周期**：比纯商贷多 1–2 周，全流程按 6–8 周排；两个还款日别记混。");
  }
  if (decisions.loan_type === "full") {
    out.push("**全款也要监管**：首付仍进预售资金监管账户，不能直接打开发商账户。");
  }
  if (decisions.project === "xiyue") {
    out.push("**现房**：手续齐的话 3 周能拿到证；重点查现售备案与物业、车位。");
  }
  if (decisions.project === "jingxi") {
    out.push("**准现房**：2027-01-30 交房，钱先付、房后到；预售资金监管账户必须核实。");
  }
  if (decisions.down_payment === "one_parent" || decisions.down_payment === "both_parent") {
    out.push("**父母出资**：走「父母 → 子女 → 监管账户」，备注赠与/借款，两层凭证都留。");
  }
  if (decisions.down_payment === "gjj") {
    out.push("**公积金提取**：顺序是「网签 → 申请提取 → 钱到本人卡」，不能拿余额顶首付；同套房提取额未到购房款总额的，中断后可再提剩余额度。");
  }
  if (decisions.down_payment === "self") {
    out.push("**自有资金**：流水要能对上首付金额，别多账户零散拼凑，大额转入要能说明来源。");
  }
  if (decisions.service === "online") {
    out.push("**只用请三次假**：网签核验、贷款面签、收房验房，其余线上办。");
  }
  return out;
}

